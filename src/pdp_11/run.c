/**
 * @file run.c
 * @brief Основной исполнительный цикл эмулятора PDP-11.
 */

#include "pdp_11/pdp_11.h"
#include "pdp_11/pdp_11_p.h"
#include "pdp_11/register/register_p.h"
#include "tests/test.h"
#include "types/types.h"

#include <stdio.h>
#include <stdlib.h>

/**
 * @brief Главный цикл выполнения команд эмулятора.
 *
 * @details Функция реализует полный цикл работы процессора:
 * 1. Инициализация внутренних структур данных через @ref pdp_create.
 * 2. Парсинг имени файла и загрузка образа программы в память.
 * 3. Установка указателя инструкции (PC) на начальный адрес (01000).
 * 4. Бесконечный цикл выборки и выполнения команд через @ref do_command.
 *
 * @param[in,out] pdp  Указатель на структуру контекста эмулятора PDP-11.
 * @param[in]     argc Количество аргументов командной строки.
 * @param[in]     argv Массив аргументов (используется для поиска входного
 * файла).
 *
 * @return Статус завершения. На данный момент всегда возвращает 0.
 *
 * @note Программа жестко закодирована на старт с восьмеричного адреса 01000.
 * @warning Цикл `while(1)` предполагает, что остановка системы происходит
 *          внутри @ref do_command (например, по инструкции HALT или ошибке).
 *
 * @todo Реализовать корректный выход из цикла при получении сигнала прерывания
 *       или выполнении специфических инструкций процессора.
 */
int
run(struct pdp_11_t *pdp, int argc, char **argv)
{
    /* Подготовка аппаратной части эмулятора */
    pdp_create(pdp);

    /* Определение целевого файла из аргументов командной строки */
    byte_t *filename = pdp_parse_filename(argc, argv);

    /* Загрузка бинарных данных в оперативную память эмулятора */
    pdp_load_data(pdp, (byte_t *) filename);
    PRINT_RESULT("\n", "");
    /** @anchor start_address
     * Точка входа в программу по умолчанию: 01000 (восьмеричная система)
     */
    address_word_t addr = 01000;

    /* Прямой доступ к внутренним регистрам для инициализации PC */
    pdp_11_t *ptr_pdp = (pdp_11_t *) pdp;
    word_t *  ptr_pc  = ptr_pdp->PC;

    /* Установка счетчика команд на стартовый адрес */
    *ptr_pc = addr;

    /**
     * @brief Исполнительный цикл (Fetch-Decode-Execute).
     */
    while (1) {
        /* Выполнение текущей команды и обновление указателя PC */
        ptr_pc = do_command(pdp, ptr_pdp->command, *ptr_pc);
    }

    /* Освобождение выделенных ресурсов */
    pdp_destroy(pdp);

    return 0;
}
