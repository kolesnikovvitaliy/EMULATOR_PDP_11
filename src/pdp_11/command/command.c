/**
 * @brief Внешний массив шаблонов базовых команд процессора
 */
extern command_t template_commands[];
byte_t           set_has_b = 0;

/**
 * @brief 📦 Инициализатор контейнера: Выделение памяти под массив команд
 * @details Аллоцирует массив указателей на команды. Размер массива жестко
 * завязан на глобальную константу @ref commands_list.
 *
 * @return command_t** Указатель на массив указателей команд, либо `NULL` при
 * критическом сбое памяти.
 *
 * @pre Константа @ref commands_list должна быть корректно определена и
 * инициализирована.
 */
command_t **
command_new(void)
{
    return (command_t **) malloc(
        (size_t) commands_list
        * sizeof(command_t *)); // Выделение памяти для объекта command_t
}

/**
 * @brief 🔨 Фабрика команд: Глубокое копирование и инициализация объектов
 * @details Проходит по всему списку выделенных указателей, аллоцирует память
 * под каждую конкретную инструкцию и заливает туда дефолтные маски и
 * обработчики из шаблонов.
 *
 * @param[in,out] commands Указатель на ранее созданный массив указателей
 * команд.
 *
 * @attention В случае неудачи `malloc` пропускает ячейку, предотвращая запись
 * по `NULL`-адресу.
 */
void
command_create(command_t **commands)
{
    for (int i = 0; i < commands_list; i++) {
        commands[i] = (command_t *) malloc(sizeof(command_t));
        if (commands[i] != NULL) {
            *commands[i] = template_commands[i];
        }
    }
}

/**
 * @brief 🪓 Утилизатор памяти: Деструктор
 * списка команд
 * @details Освобождает память, выделенную под каждую индивидуальную команду
 * внутри цикла.
 *
 * @param[in] commands Массив указателей на уничтожаемые команды.
 *
 * @note Сам массив верхнего уровня должен быть освобожден вызывающим кодом
 * отдельно через `free()`.
 */
void
command_destroy(command_t **commands)
{
    for (int i = 0; i < commands_list; i++) {
        free(commands[i]);
    }
}

/**
 * @brief 📑 Внутренний трассировщик: Логирование текущей инструкции
 * @details Выводит отладочную информацию о выполняемой команде в удобочитаемом
 * восьмеричном формате, принятом в документации по PDP-11.
 *
 * @param[in] addr Адрес в памяти (PC), где лежит инструкция.
 * @param[in] word_command 16-битное машинное слово команды.
 * @param[in] name_command Текстовая строка с мнемоникой (например, "MOV",
 * "ADD").
 */
void
__print_command(address_word_t addr, word_t word_command, byte_t *name_command)
{
    PRINT_RESULT("%06o %06o : %s", addr, word_command, name_command);
}

/**
 * @brief Функция декодирования режимов адресации процессора PDP-11.
 *
 * Данный модуль выполняет ключевую задачу эмулятора: вычисляет исполнительный
 * адрес операнда (аргумента команды) и считывает его значение из памяти или
 * регистров в зависимости от переданного режима (`mode`).
 *
 * @details
 * Архитектура PDP-11 поддерживает 8 базовых режимов адресации (0-7). Каждый
 * режим интерпретируется по-разному в зависимости от того, является ли
 * выбранный регистр общим (R0-R6) или счетчиком команд (R7 / PC). В
 * двухоперандных командах функция вызывается дважды последовательно (для
 * выборки источника `ss` и приемника `dd`).
 *
 * ### Карта режимов адресации (switch(mode)):
 * | Режим (Mode) | Название режима | Мнемоника (R0-R6) | Мнемоника для R7 (PC)
 * | Описание | | :---: | :--- | :--- | :--- | :--- | | **0** | Регистровый
 * (Register) | `Rn` | `PC` | Операнд находится в регистре. | | **1** |
 * Косвенно-регистровый (Deferred) | `(Rn)` | `(PC)` | Регистр содержит адрес
 * операнда. | | **2** | Автоинкрементный (Autoincrement) | `(Rn)+` | `#value`
 * (Immediate) | Адрес из регистра, затем регистр увеличивается. | | **3** |
 * Косвенный автоинкремент (Deferred) | `@(Rn)+` | `@#address` (Absolute) |
 * Регистр указывает на адрес адреса операнда. | | **4** | Автодекрементный
 * (Autodecrement) | `-(Rn)` | *Не рекомендуется* | Регистр уменьшается, затем
 * используется как адрес. | | **5** | Косвенный автодекремент (Deferred) |
 * `@-(Rn)`| *Не рекомендуется* | Регистр уменьшается, затем указывает на адрес
 * адреса. | | **6** | Индексный (Index) | `X(Rn)` | `X(PC)` (Relative) | Адрес
 * = `Rn` + индекс `X` (следующее слово). | | **7** | Косвенный индексный
 * (Deferred) | `@X(Rn)`| `@X(PC)` (Relative Def.)| Адрес = ячейка памяти по
 * адресу (`Rn` + `X`). |
 *
 * @param[in,out] pdp          Указатель на структуру эмулируемой машины PDP-11
 * (контекст CPU/памяти).
 * @param[in]     mode         3-битный код режима адресации (0-7), извлеченный
 * из текущей инструкции.
 * @param[in]     num_register 3-битный номер целевого регистра (0-7),
 * используемого для вычислений.
 *
 * @return arg_t res Структура, содержащая:
 *         - `res.addr`: Вычисленный исполнительный адрес (если применимо).
 *         - `res.value`: 16-битное значение (слово), прочитанное из регистра
 * или памяти.
 *
 * @note **Важно для C89/C99:** Внутри ветвления `switch` для некоторых режимов
 * (`case 3`, `case 6` и др.) объявляются локальные переменные. Перед ними
 * установлена пустая инструкция `;` для предотвращения ошибок компиляции,
 * запрещающих объявления сразу после меток `case`.
 */
arg_t
__get_args(struct pdp_11_t *pdp, word_t word_command)
{

    arg_t  res          = { 0, 0 };
    word_t num_register = word_command & 07;
    byte_t mode         = (word_command >> 3) & 07;

    switch (mode) {
        /**
         * @name      Режим адресации: Регистровый прямой (Register Direct)
         * @anchor    addressing_mode_0
         * @see       http://pdp-11.org.ru
         * @{
         */

        /**
         * @brief     Обработка **Режима 0** адресации PDP-11 (Прямая
         * регистрация).
         * @details   Данный `case` выполняется, когда метод адресации операнда
         * равен 0. Это самый быстрый режим работы процессора, так как он **не
         * обращается к оперативной памяти**. Операндом является
         * непосредственно содержимое выбранного регистра общего назначения
         * (РОН).
         *
         * ### Схема работы (Data Flow):
         * ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
         * [ Регистр (num_register) ] ---------------> [ res.value ]
         *    содержит сам операнд                       готовое значение для
         * операции
         *              |
         *              v
         *          [ res.addr ] (сохраняет индекс регистра для возможной
         * записи)
         * ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
         *
         * @param[in]  pdp          Указатель на структуру виртуальной машины
         * PDP-11.
         * @param[in]  num_register Номер целевого регистра общего назначения
         * (R0..R7).
         * @param[out] res.addr     В данном режиме — не адрес памяти, а
         * **номер (индекс) регистра**. Это критически важно для
         * инструкций-приемников (destination), чтобы знать, в какой РОН
         * записать результат.
         * @param[out] res.value    Считанное 16-битное значение
         * непосредственно из регистра @p res.addr.
         *
         * @note       Этот режим обозначается в ассемблере просто именем
         * регистра: `Rn`.
         * @warning    В режиме 0 значение @p res.addr трактуется кодом
         * выполнения команды как индекс в массиве регистров, а не как
         * указатель на ОЗУ. Попытка передать @p res.addr в функции типа
         * `w_read()` или `w_write()` приведет к критической ошибке эмуляции!
         *
         * @code
         * // Пример на ассемблере PDP-11:
         * MOV R1, R2      ; Скопировать чистое содержимое регистра R1 в
         * регистр R2 ADD R0, R3      ; Прибавить значение из R0 к значению в
         * R3
         * @endcode
         */
    case 0:
        // мода 0, R1
        /* Шаг 1: Эффективным "адресом" становится сам номер регистра */
        res.addr = num_register;

        /* Шаг 2: Извлекаем 16-битное значение напрямую из этого регистра */
        res.value = pdp_reg_get_var(pdp, res.addr);

        /* Шаг 3: Логируем операцию в стандартном для ассемблера формате Rn */
        PRINT_RESULT("R%d ", res.addr);

        break;
        /** @} */
        // мода 1, (R1)
        /**
         * @name      Режим адресации: Регистровый косвенный (Register
         * Indirect)
         * @anchor    addressing_mode_1
         * @see       http://pdp-11.org.ru
         * @{
         */

        /**
         * @brief     Обработка **Режима 1** адресации PDP-11 (Косвенная
         регистрация).
         * @details   Данный `case` выполняется, когда метод адресации операнда
         равен 1.
         *            В этом режиме указанный регистр содержит не сам операнд,
         а его
         *            **16-битный память-адрес**. Процессор считывает этот
         адрес из
         *            регистра, а затем выполняет физическое чтение данных из
         памяти.
         *
         * ### Схема работы (Data Flow):
         * ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
         * [ Регистр (num_register) ] -------> [ Память (res.addr) ] -------> [
         res.value ]
         *   содержит адрес ссылки                хранит целевое значение
         готовый операнд
         * ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
         *
         * @param[in]  pdp          Указатель на структуру виртуальной машины
         PDP-11.
         * @param[in]  num_register Номер целевого регистра общего назначения
         (R0..R7).
         * @param[out] res.addr     Вычисленный эффективный адрес в памяти
         процессора.
         * @param[out] res.value    Считанное 16-битное значение (слово) по
         адресу @p res.addr.
         *
         * @note       Этот режим часто обозначается в ассемблере как `(Rn)`.

         *
         * @code
         * // Пример на ассемблере PDP-11:
         * MOV (R1), R2    ; Переслать значение из адреса, лежащего в R1, в
         регистр R2
         * @endcode
         */
    case 1:
        /* Шаг 1: Извлекаем из регистра адрес ячейки памяти */
        res.addr = pdp_reg_get_var(pdp, num_register);
        /* Шаг 2: Выполняем чтение 16-битного слова из шины памяти по этому
         * адресу */
        res.value = w_read(pdp, res.addr);
        /* Шаг 3: Логируем операцию для отладки в формате (Rn) */
        PRINT_RESULT("(R%d) ", num_register);
        break;
        /** @} */
        // мода 2, (R1)+ или #3
        /**
         * @brief Обработка режима адресации 2: Косвенно-автоинкрементный
         * (Autoincrement)
         *
         * Данный блок реализует логику выполнения второй функции метода
         * адресации процессора PDP-11. Режим производит чтение значения по
         * адресу, хранящемуся в регистре, с последующим увеличением этого
         * регистра на размер слова (2 байта).
         *
         * @details
         * ### Алгоритм работы:
         * 1. **Получение адреса**: Считывается текущее значение из выбранного
         * регистра `num_register` и сохраняется в структуру результата
         * `res.addr`. Это базовый адрес для текущей операции.
         * 2. **Автоинкремент**: Значение регистра немедленно увеличивается на
         * 2 (размер слова для адресации `address_word_t`) и записывается
         * обратно в регистр через `pdp_reg_set_var`.
         * 3. **Ветвление логики (PC vs Общие регистры)**:
         *    - **Регистр R7 (Program Counter - PC)**:
         *      - Используется для выборки непосредственного операнда
         * (Literal/Immediate data).
         *      - Так как значение счетчика команд уже изменилось, физическое
         * чтение данных из памяти выполняется по смещенному адресу `res.addr +
         * 2`.
         *      - Осуществляется вывод отладочной мнемоники в формате `#value`
         * (например, `#001234 `).
         *    - **Регистры R0-R6**:
         *      - Выполняется стандартное чтение слова из памяти по исходному
         * адресу `res.addr`.
         *      - Осуществляется вывод классической мнемоники автоинкремента в
         * формате `(Rn)+ ` (например, `(R3)+ `).
         *
         * @param[in,out] pdp          Указатель на структуру эмулируемой
         * машины PDP.
         * @param[in]     num_register Номер обрабатываемого регистра (0-7).
         * @param[out]    res.addr     Зафиксированный адрес источника или
         * назначения.
         * @param[out]    res.value    Считанное из памяти 16-битное слово
         * данных.
         *
         * @note Комментарий "ss - откуда, dd - куда" в коде указывает на
         * универсальность данного кейса. Он вызывается как для декодирования
         * источника (source), так и для приемника (destination) в
         * двухоперандных командах.
         *
         * @see pdp_reg_get_var()
         * @see pdp_reg_set_var()
         * @see w_read()
         */
    case 2:
        res.addr
            = pdp_reg_get_var(pdp, num_register); // ss -откуда, dd - куда;

        if (set_has_b && (!(num_register == 7 || num_register == 6))) {
            pdp_reg_set_var(pdp, num_register, (address_byte_t)(res.addr + 1));
        } else {
            pdp_reg_set_var(pdp, num_register, (address_word_t)(res.addr + 2));
        }

        // печать разной мнемоники для PC и других регистров
        if (num_register == 7 || num_register == 6) {
            res.value = (word_t) w_read(pdp, (address_word_t)(res.addr + 2));
            PRINT_RESULT("#%o ", res.value);
            break;
        } else {
            if (set_has_b) {
                res.value = (word_t)(
                    signed char) ((b_read(pdp, (address_byte_t)(res.addr))));
                set_has_b = 0;
            } else {
                res.value = (word_t) w_read(pdp, (address_word_t)(res.addr));
            }
            PRINT_RESULT("(R%d)+ ", num_register);
        }

        break;
        /**
         * @brief Обработка режима адресации 3: Косвенный автоинкрементный
         * (Autoincrement Deferred)
         *
         * Данный блок реализует логику третьей функции метода адресации
         * процессора PDP-11. Режим использует указатель на указатель: из
         * регистра считывается адрес ячейки памяти, в которой хранится
         * *окончательный (исполнительный) адрес* операнда. После извлечения
         * адреса значение самого регистра автоматически увеличивается на
         * размер слова (2 байта).
         *
         * @details
         * ### Особенности синтаксиса Си:
         * Использование пустой инструкции `;` сразу после метки `case 3:`
         * является обязательным по стандарту ISO C (до C23), так как
         * объявление переменной `temp_value_register` не может следовать сразу
         * за меткой без предшествующего оператора.
         *
         * ### Алгоритм работы:
         * 1. **Резервирование и инкремент**:
         *    - Извлекается базовый адрес из `num_register`.
         *    - Рассчитывается новое значение регистра с учетом автоинкремента
         * (`+2`).
         *    - Обновленный адрес немедленно записывается обратно в регистр
         * через `pdp_reg_set_var`.
         * 2. **Разрешение косвенной адресации (Ветвление)**:
         *    - **Регистр R7 (Program Counter - PC)** [Абсолютная адресация
         * `@#`]:
         *      - Из памяти по смещенному адресу `inc_addr_offset` вычитывается
         * исполнительный адрес.
         *      - По полученному адресу `res.addr` производится чтение
         * итогового значения `res.value`.
         *      - Печатается абсолютная мнемоника в восьмеричном формате
         * (например, `@#001234 `).
         *    - **Регистры R0-R6** [Косвенный автоинкремент `@(Rn)+`]:
         *      - Из памяти по исходному адресу `temp_value_register`
         * извлекается исполнительный адрес.
         *      - По полученному адресу `res.addr` производится чтение
         * итогового значения `res.value`.
         *      - Печатается классическая мнемоника режима (например, `@(R3)+
         * `).
         *
         * @param[in,out] pdp          Указатель на структуру эмулируемой
         * машины PDP.
         * @param[in]     num_register Номер обрабатываемого регистра (0-7).
         * @param[out]    res.addr     Вычисленный исполнительный адрес
         * операнда в памяти.
         * @param[out]    res.value    Итоговое 16-битное слово данных,
         * считанное по адресу `res.addr`.
         *
         * @see pdp_reg_get_var()
         * @see pdp_reg_set_var()
         * @see w_read()
         */
    case 3:; //  для объявления типа данных address_word_t требуется " ; "
             //  после метки
        address_word_t temp_value_register
            = (word_t) pdp_reg_get_var(pdp, num_register); // 1002

        address_word_t inc_addr_offset
            = (address_word_t)(temp_value_register + 2); // 1004

        // ss -откуда, dd - куда;
        pdp_reg_set_var(pdp, num_register, (address_word_t)(inc_addr_offset));

        if (num_register == 7) {
            address_word_t addr_reg_pc = (address_word_t)(
                w_read(pdp, (address_word_t)(inc_addr_offset)));

            res.addr  = addr_reg_pc;
            res.value = w_read(pdp, (address_word_t)(res.addr));

            PRINT_RESULT("@#%o ", res.addr);
        } else {
            address_word_t addr_top = (address_word_t)(
                w_read(pdp, (address_word_t)(temp_value_register)));

            res.addr  = addr_top;
            res.value = w_read(pdp, (address_word_t)(res.addr));

            PRINT_RESULT("@(R%d)+ ", num_register);
        }
        // __command_reg_dump(pdp);

        break;
        /**
         * @brief Обработка режима адресации 4: Автодекрементный
         * (Autodecrement)
         *
         * Данный блок реализует логику выполнения четвертой функции метода
         * адресации процессора PDP-11. Режим сначала уменьшает значение
         * указанного регистра на размер слова (2 байта), а затем использует
         * обновленное значение в качестве исполнительного адреса для чтения
         * операнда из памяти.
         *
         * @details
         * Использование пустой инструкции `;` сразу после метки `case 4:`
         * необходимо по стандарту ISO C для корректного объявления локальной
         * переменной `t_var_reg`.
         *
         * ### Алгоритм работы:
         * 1. **Извлечение текущего значения**: Функция `pdp_reg_get_var`
         * считывает текущее содержимое регистра `num_register` во временную
         * переменную `t_var_reg`.
         * 2. **Предварительный декремент (Pre-decrement)**:
         *    - Из полученного значения вычитается 2 байта (размер машинного
         * слова).
         *    - Модифицированный адрес записывается обратно в регистр через
         * `pdp_reg_set_var`.
         *    - *Заметка разработчика (TODO)*: При обработке байтовых
         * инструкций (например, `MOVB`, `CMPB`) для общих регистров `R0-R5`
         * декремент должен составлять `1` байт, а для системных `R6` (SP) и
         * `R7` (PC) — всегда `2` байта для сохранения выравнивания сетки
         * памяти.
         * 3. **Фиксация исполнительного адреса**: Измененное состояние
         * регистра повторно считывается и сохраняется в `res.addr` как
         * итоговый целевой адрес.
         * 4. **Чтение данных**: С помощью функции `w_read` из памяти по адресу
         * `res.addr` выбирается целевое 16-битное слово данных и помещается в
         * `res.value`.
         * 5. **Трассировка**: Осуществляется вывод классической ассемблерной
         * мнемоники автодекремента в формате `-(Rn)` (например, `-(R4) `).
         *
         * @param[in,out] pdp          Указатель на структуру эмулируемой
         * машины PDP.
         * @param[in]     num_register Номер обрабатываемого регистра (0-7).
         * @param[out]    res.addr     Вычисленный исполнительный адрес
         * (уменьшенное значение регистра).
         * @param[out]    res.value    Считанное из памяти по новому адресу
         * 16-битное слово данных.
         *
         * @warning Использование режима 4 с регистром `R7 (PC)` технически
         * возможно, но крайне не рекомендуется (unpredictable), так как
         * уменьшение счетчика команд на шаг декодирования может привести к
         * зацикливанию процессора или порче выполняемого кода.
         *
         * @see pdp_reg_get_var()
         * @see pdp_reg_set_var()
         * @see w_read()
         */
    case 4:; //  для объявления типа данных word_t требуется " ; " после метки
        res.addr = (address_word_t)(pdp_reg_get_var(pdp, num_register));

        if (set_has_b && (!(num_register == 7 || num_register == 6))) {

            res.value = (word_t)(
                signed char) (b_read(pdp, (address_byte_t)(res.addr)));

        } else {

            res.value = (word_t) w_read(pdp, (address_word_t)(res.addr));
        }

        if (set_has_b && (!(num_register == 7 || num_register == 6))) {

            pdp_reg_set_var(pdp, num_register, (address_byte_t)(res.addr - 1));

        } else {

            pdp_reg_set_var(pdp, num_register, (address_word_t)(res.addr - 2));
        }

        if (res.addr <= 010) {

            res.value = 0;
        }

        // __command_reg_dump(pdp);
        PRINT_RESULT("-(R%d) ", num_register);
        break;

        /**
         * @brief Обработка режима адресации 5: Косвенный автодекрементный
         * (Autodecrement Deferred)
         *
         * Данный блок реализует логику выполнения пятой функции метода
         * адресации процессора PDP-11. Этот режим сочетает предварительное
         * уменьшение регистра и косвенную адресацию: сначала значение
         * указанного регистра уменьшается на размер слова (всегда на 2 байта),
         * после чего полученное значение используется как адрес ячейки памяти,
         * где хранится *исполнительный адрес* операнда.
         *
         * @details
         * Использование пустой инструкции `;` сразу после метки `case 5:`
         * необходимо по стандарту ISO C для корректного размещения объявлений
         * или использования переменных в контексте блока `switch-case`.
         *
         * ### Алгоритм работы:
         * 1. **Чтение и вычисление декремента (Pre-decrement)**:
         *    - Из регистра `num_register` извлекается текущее значение и
         * сохраняется в `temp_value_register`.
         *    - Рассчитывается уменьшенный адрес `inc_addr_offset` путем
         * вычитания 2 байт.
         *    - *Архитектурная деталь*: В отличие от режима 4, в режиме 5
         * значение регистра
         *      **всегда** уменьшается на 2, даже если выполняется байтовая
         * инструкция. Это обусловлено тем, что регистр содержит адрес
         * указателя, а указатели в PDP-11 всегда занимают целое слово (2
         * байта).
         * 2. **Чтение исполнительного адреса (Косвенность)**:
         *    - С помощью функции `w_read` из памяти по вычисленному адресу
         * `inc_addr_offset` вычитывается 16-битный указатель — истинный адрес
         * операнда `addr_top`.
         * 3. **Обновление состояния процессора**:
         *    - Новое уменьшенное значение `inc_addr_offset` записывается
         * обратно в регистр через функцию `pdp_reg_set_var`.
         * 4. **Выборка операнда**:
         *    - Исполнительный адрес фиксируется в структуре результата:
         * `res.addr = addr_top`.
         *    - По этому адресу из памяти считывается итоговое значение данных:
         * `res.value`.
         * 5. **Трассировка**:
         *    - Выводится классическая ассемблерная мнемоника косвенного
         * автодекремента в формате `@-(Rn)` (например, `@-(R2) `).
         *
         * @param[in,out] pdp          Указатель на структуру эмулируемой
         * машины PDP.
         * @param[in]     num_register Номер обрабатываемого регистра (0-7).
         * @param[out]    res.addr     Вычисленный исполнительный адрес
         * операнда (извлеченный из указателя).
         * @param[out]    res.value    Итоговое 16-битное слово данных,
         * считанное по адресу `res.addr`.
         *
         * @note Комментарий "ss - откуда, dd - куда" подчеркивает, что
         * алгоритм получения косвенного адреса идентичен как для
         * операнда-источника, так и для операнда-приемника.
         *
         * @see pdp_reg_get_var()
         * @see pdp_reg_set_var()
         * @see w_read()
         */
    case 5:; //  для объявления типа данных word_t требуется " ; " после метки

        temp_value_register = (word_t) pdp_reg_get_var(pdp, num_register);

        inc_addr_offset = (address_word_t)(temp_value_register - 2);

        address_word_t addr_top
            = (address_word_t)(w_read(pdp, (address_word_t)(inc_addr_offset)));

        pdp_reg_set_var(pdp, num_register, (address_word_t)(inc_addr_offset));

        res.addr  = addr_top;
        res.value = w_read(pdp, (address_word_t)(res.addr));
        // ss -откуда, dd - куда;

        PRINT_RESULT("@-(R%d) ", num_register);

        break;
        /**
         * @brief Обработка режима адресации 6: Индексный / Относительный
         * (Index / Relative)
         *
         * Данный блок реализует шестую функцию метода адресации процессора
         * PDP-11. Этот режим вычисляет исполнительный адрес путем сложения
         * содержимого выбранного регистра со смещением (индексом) X, которое
         * хранится в следующем за командой слове памяти.
         *
         * @details
         * Использование пустой инструкции `;` сразу после метки `case 6:`
         * необходимо по стандарту ISO C для корректного объявления локальных
         * переменных внутри блока выбора.
         *
         * ### Алгоритм работы:
         * 1. **Выборка индекса X (Чтение из PC)**:
         *    - Запрашивается текущее состояние счетчика команд `R7 (PC)`.
         *    - Функция `w_read` считывает значение индекса `word_in_mem` из
         * памяти по адресу `PC + 2`.
         *    - Счетчик команд немедленно сдвигается вперед (`PC = PC + 2`),
         * фиксируя прохождение ячейки с индексом.
         * 2. **Базовое вычисление адреса**:
         *    - Извлекается значение базового регистра `num_register` и
         * сохраняется в `res.addr`.
         *    - Вычисляется финальный исполнительный адрес: к значению регистра
         * прибавляется считанный индекс `word_in_mem`.
         *    - По полученному адресу из памяти вычитывается итоговый операнд
         * `res.value`.
         * 3. **Ветвление логики (PC vs Общие регистры)**:
         *    - **Регистр R7 (Program Counter - PC) [Относительный режим]**:
         *      - В ассемблере PDP-11 конструкция `X(PC)` превращается в
         * относительную адресацию (`A`).
         *      - Текущая реализация ветки `if (num_register == 7)` содержит
         * специфическую логику эмуляции: счетчик команд `PC` продвигается еще
         * раз на 2 байта вперед, после чего вычисляется относительное
         * смещение, и результат выводится на печать в виде восьмеричного
         * адреса.
         *    - **Регистры R0-R6 [Индексный режим]**:
         *      - Выполняется классический вывод трассировки индексного режима
         * в формате `X(Rn)`.
         *      - Печатается десятичное значение смещения и номер регистра,
         * например: `4(R2) `.
         *
         * @param[in,out] pdp          Указатель на структуру эмулируемой
         * машины PDP.
         * @param[in]     num_register Номер обрабатываемого регистра (0-7).
         * @param[out]    res.addr     Итоговый вычисленный исполнительный
         * адрес операнда.
         * @param[out]    res.value    16-битное слово данных, извлеченное по
         * целевому адресу.
         *
         * @see pdp_reg_get_var()
         * @see pdp_reg_set_var()
         * @see w_read()
         */
    case 6:;
        address_word_t addr_in_pc  = (address_word_t) pdp_reg_get_var(pdp, 7);
        word_t         word_in_mem = w_read(pdp, (word_t)(addr_in_pc + 2));
        pdp_reg_set_var(pdp, 7, (address_word_t)(addr_in_pc + 2));

        res.addr = pdp_reg_get_var(pdp, num_register);
        res.addr = (word_t)(res.addr + word_in_mem);

        res.value = (word_t) w_read(pdp, res.addr);

        if (num_register == 7) {
            // addr_in_pc = (address_word_t)(pdp_reg_get_var(pdp, 7));

            addr_in_pc = (address_word_t)(pdp_reg_get_var(pdp, 7));
            // PRINT_RESULT("\nADR_IN_PC = %o\n", addr_in_pc);
            word_in_mem = (word_t)(addr_in_pc + word_in_mem);
            // PRINT_RESULT("\nword_in_mem = %o\n", word_in_mem);

            res.value = word_in_mem;
            PRINT_RESULT("%o ", res.value);
        } else {
            PRINT_RESULT("%o(R%d) ", word_in_mem, num_register);
        }
        break;
        /**
         * @brief Обработка режима адресации 7: Косвенный индексный / Косвенный
         * относительный (Index Deferred / Relative Deferred)
         *
         * Данный блок реализует логику финальной, седьмой функции метода
         * адресации процессора PDP-11. Режим представляет собой сложную
         * многоуровневую структуру: к базовому регистру прибавляется индекс
         * (смещение) X, извлеченный из памяти, формируя указатель. По этому
         * указателю извлекается *исполнительный адрес*, и только затем по нему
         * считывается итоговое значение операнда.
         *
         * @details
         * Использование пустой инструкции `;` сразу после метки `case 7:`
         * необходимо по стандарту ISO C для корректной локализации и
         * инициализации переменной `temp_addr`.
         *
         * ### Архитектурный алгоритм работы:
         * 1. **Выборка смещения X (Продвижение PC)**:
         *    - Извлекается текущее значение счетчика команд `R7 (PC)`.
         *    - Модификатор `PC = PC + 2` резервирует шаг для безопасного
         * извлечения данных.
         *    - Функция `w_read` считывает значение 16-битного смещения
         * `offset` из памяти.
         *    - Счетчик команд `PC` сдвигается еще раз на 2 байта вперед (`PC =
         * PC + 2`), указывая на следующую за смещением инструкцию.
         * 2. **Разрешение адресации (Ветвление)**:
         *    - **Регистр R7 (Program Counter - PC) [Косвенный относительный
         * режим `@A`]**:
         *      - Базовым адресом выступает уже дважды сдвинутый `PC`.
         *      - Вычисляется адрес указателя: `res.addr = offset + PC`.
         *      - Из вычисленной ячейки извлекается исполнительный адрес:
         * `temp_addr = w_read(pdp, res.addr)`.
         *      - По итоговому адресу вычитываются целевые данные: `res.value =
         * w_read(pdp, temp_addr)`.
         *      - Осуществляется вывод отладочной мнемоники с префиксом
         * косвенности `@` в восьмеричном виде (например, `@001234 `).
         *    - **Регистры R0-R6 [Косвенный индексный режим `@X(Rn)`]**:
         *      - Извлекается базовое значение из регистра `num_register`.
         *      - Вычисляется промежуточный адрес указателя: `res.addr = offset
         * + Rn`.
         *      - Происходит чтение исполнительного адреса из памяти: `res.addr
         * = w_read(pdp, res.addr)`.
         *      - По новому обновленному адресу вычитывается операнд:
         * `res.value = w_read(pdp, res.addr)`.
         *      - Формируется классическая трассировка формата `@X(Rn)`, где
         * смещение выводится в восьмеричной системе (например, `@4(R2) `).
         *
         * @param[in,out] pdp          Указатель на структуру эмулируемой
         * машины PDP.
         * @param[in]     num_register Номер обрабатываемого регистра (0-7).
         * @param[out]    res.addr     Вычисленный исполнительный адрес
         * операнда (конечная точка в памяти).
         * @param[out]    res.value    Итоговое 16-битное слово данных,
         * извлеченное для выполнения команды.
         *
         * @see pdp_reg_get_var()
         * @see pdp_reg_set_var()
         * @see w_read()
         */
    case 7:;
        word_t temp_addr = 00;
        addr_in_pc       = (address_word_t) pdp_reg_get_var(pdp, 7);
        pdp_reg_set_var(pdp, 7, (address_word_t)(addr_in_pc + 2));

        addr_in_pc = (address_word_t) pdp_reg_get_var(pdp, 7);

        word_t offset = w_read(pdp, (word_t)(addr_in_pc));

        pdp_reg_set_var(pdp, 7, (address_word_t)(addr_in_pc + 2));

        if (num_register == 7) {
            res.addr = pdp_reg_get_var(pdp, 7);

            res.addr = (word_t)(offset + res.addr);

            temp_addr = w_read(pdp, res.addr);

            res.value = w_read(pdp, temp_addr);

            PRINT_RESULT("@%o ", res.addr);

        } else {
            res.addr = pdp_reg_get_var(pdp, num_register);

            res.addr = (word_t)(offset + res.addr);

            res.addr = w_read(pdp, res.addr);

            res.value = w_read(pdp, res.addr);

            PRINT_RESULT("@%o(R%d) ", offset, num_register);
        }

        break;
    default:
        ERROR_LOG("\nMode %d not implemented yet!\n", mode);
        exit(1);
    }
    return res;
}

/**
 * @brief Декодирует операнды и параметры инструкции PDP-11 на основе маски
 * параметров.
 *
 * Функция разбирает 16-битное слово команды `word_command`, извлекая из него
 * адреса/значения источников (SS), приемников (DD), регистров (R) или констант
 * (N, NN, XX) в соответствии с переданным флагом `param`.
 *
 * @details
 * ### Схема расположения полей в инструкциях PDP-11:
 * - `DD` (Destination): Биты [0..5] (6 бит: 3 режим, 3 регистр)
 * - `SS` (Source):      Биты [6..11] (6 бит: 3 режим, 3 регистр)
 * - `R`  (Register):    Биты [6..8] (3 бита)
 * - `N`/`NN` (Numbers): Младшие биты в зависимости от формата команды
 * - `XX` (Offset):      Биты [0..7] (8 бит со знаком для ветвлений)
 *
 * @param[in,out] pdp          Указатель на структуру эмулируемой машины
 * PDP-11.
 * @param[in]     word_command Полное 16-битное слово текущей команды.
 * @param[in]     param        Битовая маска (флаги), определяющая архитектуру
 * команды.
 *
 * @return op_code_t Структура с заполненными аргументами для выполнения
 * операции.
 */
op_code_t
__get_mr(struct pdp_11_t *pdp, word_t word_command, byte_t param)
{
    op_code_t opcode = { 0 };

    // Если у команды нет параметров (например, HALT, RESET, NOP)
    if (param & NO_PARAMS) {
        return opcode;
    }
    if (param & HAS_B) {
        // Сдвигаем на 6 бит вправо и накладываем маску 077 (6 бит)
        set_has_b = 1;
    }
    // 2. Извлечение поля DESTINATION (DD): всегда биты [0..5]
    // if (param & HAS_DD) {
    //     // Младшие 6 бит слова команды
    //     opcode.dd = __get_args(pdp, word_command & 077);
    // }
    // 1. Извлечение поля SOURCE (SS): всегда биты [6..11]
    if (param & HAS_SS) {
        // Сдвигаем на 6 бит вправо и накладываем маску 077 (6 бит)
        opcode.ss = __get_args(pdp, (word_command >> 6) & 077);
    }

    // 2. Извлечение поля DESTINATION (DD): всегда биты [0..5]
    if (param & HAS_DD) {
        // Младшие 6 бит слова команды
        opcode.dd = __get_args(pdp, word_command & 077);
    }

    // 3. Извлечение чистого регистра R (например, в JSR R, DD или RTS R)
    if (param & HAS_R) {
        // Регистр обычно находится в битах [6..8]
        opcode.r_reg = (word_command >> 6) & 07;
    }

    // 4. Извлечение литералов N / NN (значения записываются в специальные поля
    // структуры)
    if (param & HAS_NN) {
        // 6-битное число, обычно в младших битах [0..5] (например, в SOB)
        opcode.value_nn = word_command & 077;
    }

    if (param & HAS_N) {
        // 3-битное число, биты [0..2]
        opcode.value_n = word_command & 07;
    }

    // 5. Извлечение знакового смещения XX для ветвлений (Branch instructions)
    if (param & HAS_XX) {
        // Младшие 8 бит интерпретируются как значащее число от -128 до +127
        opcode.offset_xx = (word_t)(signed char) (word_command & 0xFF);
    }

    return opcode;
}
