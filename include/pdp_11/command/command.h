#ifndef COMMAND_H
#    define COMMAND_H

#    include "types/types.h"

/**
 * @struct pdp_11_t
 * @brief Неполное объявление структуры эмулятора процессора PDP-11.
 * @details Используется для предотвращения циклической зависимости (circular
 * dependency). Полное определение находится в заголовочном файле процессора.
 */
struct pdp_11_t;

/**
 * @struct command_t
 * @brief Непрозрачная структура (Opaque Structure) описания команды.
 * @details Инкапсулирует в себе внутреннее представление команды: код операции
 * (opcode), адреса операндов, флаги модификации и указатель на
 * функцию-обработчик выполнения.
 */
struct command_t;

/**
 * @brief Фабричный метод для создания и инициализации новой команды.
 * @details Выделяет память в куче (heap) под структуру команды и заполняет
 * её поля дефолтными значениями (нулями и пустами указателями).
 *
 * @note Вызывающий код полностью берет на себя ответственность за последующее
 * освобождение памяти с помощью функции command_destroy().
 *
 * @return Struct command_t* Указатель на созданную структуру в случае успеха.
 * @retval NULL Сбой выделения памяти через `malloc`.
 *
 * @see command_create()
 * @see command_destroy()
 */
struct command_t *command_new(void);

/**
 * @brief Инициализация указателя на команду с выделением памяти.
 * @details Безопасный аналог функции command_new(). Принимает двойной
 * указатель, проверяет его валидность, выделяет память под структуру и
 * записывает адрес.
 *
 * @param[out] command Двойной указатель на целевую структуру команды.
 *                     Не должен быть равен NULL. Внутри функции будет
 *                     перезаписан адресом выделенной памяти.
 *
 * @pre Передаваемый аргумент `command` должен быть валидным адресом указателя.
 * @post После успешного выполнения `*command` указывает на выделенную память.
 *
 * @code
 * struct command_t *cmd = NULL;
 * command_create(&cmd);
 * if (cmd != NULL) {
 *     // Работа с командой
 * }
 * @endcode
 */
void command_create(struct command_t **command);

/**
 * @brief Уничтожение структуры команды и освобождение ресурсов.
 * @details Освобождает память, выделенную под структуру `command_t`,
 * а также любые внутренние динамические ресурсы. После освобождения
 * зануляет переданный указатель во избежание использования после освобождения
 * (Use-After-Free).
 *
 * @param[in,out] command Двойной указатель на удаляемую структуру команды.
 *                        Если `command` равен NULL или `*command` равен NULL,
 *                        функция не совершает никаких действий (безопасное
 * удаление).
 *
 * @pre Функция ожидает указатель на ранее созданный объект через command_new()
 * или command_create().
 * @post `*command` гарантированно равен `NULL`.
 *
 * @code
 * struct command_t *cmd = command_new();
 * // ... использование команды ...
 * command_destroy(&cmd);
 * // Теперь cmd == NULL, повторный вызов command_destroy(&cmd) безопасен.
 * @endcode
 */
void command_destroy(struct command_t **command);

#endif /* COMMAND_H */
#pragma once
