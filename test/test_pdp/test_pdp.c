/**
 * @brief Глобальная переменная, определяющая текущий тип используемой памяти.
 * @details Изменяется внешней функцией конфигурации и влияет на аллокацию
 * и адресацию данных в эмуляторе.
 */
extern byte_t g_default_memory;

/**
 * @brief Установка глобального типа памяти эмулятора.
 * @param[in] type_memory Флаг или идентификатор типа памяти (например,
 * байтовая или словесная).
 * @return void
 */
void
memory_type(byte_t type_memory)
{
    g_default_memory = type_memory;
}

//////////////////////////////////////////////////////////////////////

/**
 * @brief Инициализация окружения и запуск тестов для конкретного типа памяти.
 * @details Функция выполняет полный цикл жизни объекта эмулятора для
 * изолированного теста:
 * 1. Конфигурирует тип памяти.
 * 2. Выделяет ресурсы под структуру PDP-11.
 * 3. Верифицирует успешность создания.
 * 4. Передает управление пакету тестов `all_tests`.
 * 5. Освобождает ресурсы и сбрасывает тип памяти.
 *
 * @param[in] type_memory Тип памяти, для которого запускается данный цикл
 * тестов.
 * @param[in] argc        Количество аргументов командной строки.
 * @param[in] argv        Массив строк аргументов командной строки (например,
 * пути к файлам прошивок).
 *
 * @pre Ожидается, что функции `pdp_new` и `pdp_create` корректно
 * инициализируют структуру.
 * @post Память, выделенная под `pdp`, гарантированно освобождается,
 * `g_default_memory` сбрасывается в 0.
 */
void
test_pdp_memory(byte_t type_memory, int argc, char **argv)
{
    /* Настройка конфигурации памяти перед инициализацией */
    memory_type(type_memory);

    /* Выделение памяти под контекст процессора PDP-11 */
    struct pdp_11_t *pdp = pdp_new();

    /* Первичная инициализация внутренних компонентов и регистров процессора */
    pdp_create(pdp);

    /* Критическая проверка: эмулятор должен быть успешно создан */
    assert(pdp);

    /* Вывод промежуточного статуса об успешной инициализации архитектуры */
    PRINT_RESULT("%s", " ... OK\n");

    /* Запуск комплексного набора тестов (команды, регистры, логика) */
    all_tests(pdp, argc, argv);

    /* Деинициализация внутренних структур процессора */
    pdp_destroy(pdp);

    /* Освобождение самого контейнера структуры */
    free(pdp);

    /* Сброс конфигурации памяти в безопасное дефолтное состояние */
    memory_type((byte_t) 0);
}

//////////////////////////////////////////////////////////////////////

/**
 * @brief Главная управляющая функция модульного тестирования PDP-11.
 * @details Анализирует входные аргументы командной строки и определяет режим
 * тестирования.
 * - Если передано мало аргументов (меньше или равно 3), запускается
 * исключительно тест байтовой памяти.
 * - Если передан полный набор аргументов (включая пути к файлам),
 * последовательно тестируются оба режима: сначала `BYTE`, затем `WORD`.
 *
 * @param[in] argc Количество аргументов, переданных при запуске бинарного
 * файла.
 * @param[in] argv Массив указателей на аргументы командной строки.
 *
 * @retval 0 Успешное завершение, если выполнялся только базовый тест байтовой
 * памяти.
 * @retval 1 Успешное завершение полного цикла тестов (BYTE + WORD).
 */
int
test_pdp(int argc, char **argv)
{
    /*
     * Блок отладки (закомментирован разработчиком)
     * DEBUG("\nСтартовый тест для проверки правильности\n \
     * создания и использования функций", "\r\n\n");
     */

    /* ЭТАП 1: Тестирование эмуляции с побайтовым доступом к памяти */
    WARNING_LOG("ALLOCAT MEMORY FOR CLASS MEM_BYTE_T < BYTE >", "");
    INFO_LOG("ALLOCAT MEMORY TYPE ==BYTE==", "");

    /* Проверка условий запуска: если аргументов недостаточно, файлы прошивок
     * отсутствуют */
    if (3 >= argc) {
        /* Запуск сокращенного цикла тестов только для BYTE-моды */
        test_pdp_memory(type_memory_byte, argc, argv);
        WARNING_LOG("MEMORY TYPE ==BYTE== DESTROY !!! \n", "");
        return 0;
    }

    /* Альтернативная ветка: аргументов достаточно, запускаем полный цикл */
    test_pdp_memory(type_memory_byte, argc, argv);
    WARNING_LOG("MEMORY TYPE ==BYTE== DESTROY !!! \n", "");

    /* ЭТАП 2: Тестирование эмуляции со словесным (16-бит) доступом к памяти */
    WARNING_LOG("ALLOCAT MEMORY FOR CLASS MEM_WORD_T < WORD >", "");
    INFO_LOG("ALLOCAT MEMORY TYPE ==WORD== !!!", "");

    /* Запуск цикла тестов для WORD-моды */
    test_pdp_memory(type_memory_word, argc, argv);
    WARNING_LOG("MEMORY ==WORD== DESTROY !!! \n", "");

    /* Финальный лог, свидетельствующий о прохождении всех тестовых наборов */
    INFO_LOG("ALL TESTS PDP_11 PASSED SUCCESSFULLY\n", "");
    return 1;
}
