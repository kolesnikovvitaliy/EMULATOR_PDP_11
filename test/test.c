/**
 * @file test.c
 * @brief Агрегатор модульных тестов эмулятора.
 */

#include "tests/test_pdp/test_io/test_io.h"
#include "tests/test_pdp/test_memory/test_memory.h"
#include "tests/test_pdp/test_reg/test_reg.h"

#include <assert.h>
#include <stdio.h>
#include <stdlib.h>

/**
 * @brief Запуск полной подсистемы тестирования компонентов PDP-11.
 *
 * @details Данная функция является центральным узлом для верификации
 * эмулятора. Она последовательно вызывает наборы тестов для отдельных модулей
 * системы.
 *
 * Текущий порядок выполнения:
 * 1. Тестирование подсистемы памяти (@ref test_memory).
 * 2. Тестирование операций ввода-вывода (@ref test_io).
 *
 * @param[in,out] pdp  Указатель на контекст эмулятора для проведения тестов.
 * @param[in]     argc Количество аргументов (для фильтрации тестов, если
 * реализовано).
 * @param[in]     argv Массив аргументов командной строки.
 *
 * @note Если любой из внутренних тестов завершится неудачей, выполнение
 *       будет прервано (в зависимости от реализации макросов в тестах).
 *
 * @todo Добавить блок @ref test_registers для проверки корректности работы
 *       регистров общего назначения и флагов состояния (PSW).
 */
void
all_tests(struct pdp_11_t *pdp, int argc, char **argv)
{
    /* Верификация подсистемы оперативной памяти */
    test_memory(pdp, argc, argv);

    /* Верификация подсистемы обмена данными (IO) */
    test_io(pdp, argc, argv);

    /* Верификация подсистемы регистров (R0-R7) */
    test_reg(pdp);

    // TODO Слздать тесты выполнения команд с разными модами
}
